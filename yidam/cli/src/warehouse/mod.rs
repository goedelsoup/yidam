//! RFC-0049: the ontology as the schema a pipeline loads into and a semantic layer reads.
//!
//! [`contract`] derives one dialect-free model from the classes, the dialect renderers read
//! it, and [`ownership`] decides what a re-export may overwrite. yidam writes text here and
//! runs none of it: no connection to a warehouse is opened.

pub(crate) mod bigquery;
pub(crate) mod contract;
pub(crate) mod feeds;
pub(crate) mod ownership;
pub(crate) mod textql;

use std::collections::BTreeSet;
use std::path::Path;

use anyhow::{bail, Context, Result};

use crate::corpus::Class;
use crate::model::DomainModel;

/// The marker every file this module generates carries on its first line.
pub(crate) const MARKER: &str = "Generated by `yidam export --format warehouse` from this \
                                 corpus's ontology. Regenerate rather than edit; an edited file \
                                 is refused on the next export.";

/// The part of [`MARKER`] a later release may not change, since it is what finds the files.
pub(crate) const MARKER_PREFIX: &str = "Generated by `yidam export --format warehouse`";

/// The generator name the manifest records.
pub(crate) const GENERATOR: &str = "yidam export --format warehouse";

/// The contract's own version: it rises when a reader of `contract.json` would mis-read it.
const CONTRACT_FORMAT_VERSION: u32 = 1;

/// Parse the model's classes the way every other reader of `.ont.yml` does.
pub(crate) fn classes(model: &DomainModel) -> Vec<Class> {
    model
        .classes
        .iter()
        .map(|c| {
            Class::parse(
                format!(".yidam/corpus/{}", c.filename),
                String::from_utf8_lossy(&c.content),
            )
        })
        .collect()
}

/// Derive the contract, turning its refusals into one error that lists them all.
pub(crate) fn contract(model: &DomainModel) -> Result<contract::Contract> {
    match contract::derive(&classes(model)) {
        Ok(c) => Ok(c),
        Err(refusals) => bail!(
            "The ontology cannot be placed in a warehouse contract as it stands. Nothing was \
             written:\n  - {}",
            refusals.join("\n  - ")
        ),
    }
}

fn contract_json(contract: &contract::Contract) -> Result<String> {
    #[derive(serde::Serialize)]
    struct Envelope<'a> {
        #[serde(rename = "$comment")]
        comment: &'a str,
        format_version: u32,
        #[serde(flatten)]
        contract: &'a contract::Contract,
    }
    let mut body = serde_json::to_string_pretty(&Envelope {
        comment: MARKER,
        format_version: CONTRACT_FORMAT_VERSION,
        contract,
    })?;
    body.push('\n');
    Ok(body)
}

/// Where a corpus declares its feeds (§3.1).
pub(crate) const FEEDS_DIR: &str = ".yidam/warehouse/feeds";

/// What the warehouse export reads besides the ontology: the feed files, and the catalog
/// slugs a feed's `source:` must name.
pub(crate) struct Inputs {
    pub feeds: Vec<feeds::FeedSource>,
    pub catalog: BTreeSet<String>,
}

impl Inputs {
    pub(crate) fn load(root: &Path) -> Result<Self> {
        let dir = root.join(FEEDS_DIR);
        let mut feeds = Vec::new();
        if dir.is_dir() {
            for entry in
                std::fs::read_dir(&dir).with_context(|| format!("reading {}", dir.display()))?
            {
                let path = entry?.path();
                if path.extension().and_then(|x| x.to_str()) != Some("yml") {
                    continue;
                }
                let stem = path
                    .file_stem()
                    .and_then(|s| s.to_str())
                    .unwrap_or_default();
                feeds.push(feeds::FeedSource {
                    rel: format!("{FEEDS_DIR}/{stem}.yml"),
                    stem: stem.to_string(),
                    text: std::fs::read_to_string(&path)
                        .with_context(|| format!("reading {}", path.display()))?,
                });
            }
        }
        feeds.sort_by(|a, b| a.stem.cmp(&b.stem));
        let catalog = crate::walk::walk_md_files(&crate::paths::yidam_catalog_dir(root))
            .iter()
            .filter_map(|p| p.file_stem().and_then(|s| s.to_str()).map(String::from))
            .collect();
        Ok(Self { feeds, catalog })
    }
}

/// What `export --format warehouse` produced.
pub(crate) struct Rendered {
    /// Every file, as output-relative path and bytes.
    pub files: Vec<(String, Vec<u8>)>,
    /// The feeds that were resolved, by name.
    pub feeds: Vec<String>,
    /// Classes no feed maps: coverage, reported and never refused (§3.2).
    pub unmapped: Vec<String>,
}

fn resolve_feeds(contract: &contract::Contract, inputs: &Inputs) -> Result<Vec<feeds::Feed>> {
    match feeds::resolve(&inputs.feeds, contract, &inputs.catalog) {
        Ok(f) => Ok(f),
        Err(refusals) => bail!(
            "A feed does not fit the warehouse contract. Nothing was written:\n  - {}",
            refusals.join("\n  - ")
        ),
    }
}

/// Derive the contract, resolve the feeds against it, and render both.
pub(crate) fn render_warehouse(model: &DomainModel, inputs: &Inputs) -> Result<Rendered> {
    let contract = contract(model)?;
    let resolved = resolve_feeds(&contract, inputs)?;
    let mut files = vec![
        (
            "contract.json".to_string(),
            contract_json(&contract)?.into_bytes(),
        ),
        (
            "ddl/bigquery/0001_init.sql".to_string(),
            bigquery::render_init(&contract).into_bytes(),
        ),
    ];
    files.extend(
        bigquery::render_feeds(&resolved)
            .into_iter()
            .map(|(p, s)| (p, s.into_bytes())),
    );
    Ok(Rendered {
        files,
        unmapped: feeds::unmapped(&contract, &resolved),
        feeds: resolved.into_iter().map(|f| f.name).collect(),
    })
}

/// Render the `textql` folder (§5): the same contract and feeds the warehouse export reads,
/// so a page cannot name a column the DDL does not create.
pub(crate) fn render_textql(
    model: &DomainModel,
    inputs: &Inputs,
    prefix: &str,
) -> Result<textql::Folder> {
    let contract = contract(model)?;
    let resolved = resolve_feeds(&contract, inputs)?;
    Ok(textql::render(
        &classes(model),
        &contract,
        &resolved,
        prefix,
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{OntClass, RenderedViews};

    fn model(classes: &[(&str, &str)]) -> DomainModel {
        DomainModel {
            classes: classes
                .iter()
                .map(|(name, yaml)| OntClass {
                    filename: format!("{name}.ont.yml"),
                    content: yaml.as_bytes().to_vec(),
                })
                .collect(),
            instances: vec![],
            skills: vec![],
            decisions: vec![],
            index: None,
            provenance: crate::model::test_provenance(),
            rendered: RenderedViews {
                corpus_index: String::new(),
                graph_check: String::new(),
                decisions_log: String::new(),
                skills_index: String::new(),
            },
        }
    }

    /// A small cloud-inventory ontology: one value set, one date, one claim, one edge each way.
    fn fixture() -> DomainModel {
        model(&[
            (
                "compute-instance",
                "label: Compute instance\n\
                 description: A virtual machine in a cloud provider's inventory.\n\
                 properties:\n\
                 \x20 - name: provider\n    type: string\n    required: true\n    \
                 values: [gcp, aws]\n\
                 \x20 - name: machine-type\n    type: string\n\
                 \x20 - name: vcpus\n    type: number\n\
                 \x20 - name: created\n    type: date\n\
                 \x20 - name: standing\n    type: claim\n\
                 edges:\n\
                 \x20 - relationship: attached-to\n    target: network\n    direction: out\n",
            ),
            (
                "network",
                "label: Network\n\
                 properties:\n  - name: cidr\n    type: string\n\
                 edges:\n\
                 \x20 - relationship: attached-to\n    target: compute-instance\n    \
                 direction: in\n",
            ),
        ])
    }

    fn inputs() -> Inputs {
        Inputs {
            feeds: vec![feeds::tests::source("gcp-cai", feeds::tests::CAI)],
            catalog: feeds::tests::catalog(),
        }
    }

    fn rendered() -> Vec<(String, String)> {
        render_warehouse(&fixture(), &inputs())
            .unwrap()
            .files
            .into_iter()
            .map(|(p, b)| (p, String::from_utf8(b).unwrap()))
            .collect()
    }

    #[test]
    fn the_fixture_renders_to_its_golden() {
        for (path, body) in rendered() {
            let golden = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("tests/fixtures/warehouse")
                .join(&path);
            if std::env::var_os("YIDAM_BLESS").is_some() {
                std::fs::create_dir_all(golden.parent().unwrap()).unwrap();
                std::fs::write(&golden, &body).unwrap();
                continue;
            }
            let want = std::fs::read_to_string(&golden).unwrap_or_else(|_| {
                panic!(
                    "missing golden {}; run with YIDAM_BLESS=1 to write it",
                    golden.display()
                )
            });
            assert_eq!(body, want, "{path} differs from its golden");
        }
    }

    #[test]
    fn every_generated_file_carries_the_marker() {
        assert!(MARKER.starts_with(MARKER_PREFIX));
        for (path, body) in rendered() {
            let head = body.lines().take(3).collect::<Vec<_>>().join("\n");
            assert!(head.contains(MARKER_PREFIX), "{path} has no marker");
        }
    }

    fn textql() -> textql::Folder {
        render_textql(&fixture(), &inputs(), "ontology/cloud").unwrap()
    }

    #[test]
    fn the_textql_folder_renders_to_its_golden() {
        for (path, body) in textql().files {
            let golden = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("tests/fixtures/textql")
                .join(&path);
            if std::env::var_os("YIDAM_BLESS").is_some() {
                std::fs::create_dir_all(golden.parent().unwrap()).unwrap();
                std::fs::write(&golden, &body).unwrap();
                continue;
            }
            let want = std::fs::read_to_string(&golden).unwrap_or_else(|_| {
                panic!(
                    "missing golden {}; run with YIDAM_BLESS=1 to write it",
                    golden.display()
                )
            });
            assert_eq!(body, want, "{path} differs from its golden");
        }
    }

    #[test]
    fn a_claim_is_prose_on_its_page_and_a_column_nowhere() {
        let folder = textql();
        let page = &folder
            .files
            .iter()
            .find(|(p, _)| p == "classes/compute-instance.md")
            .unwrap()
            .1;
        let prose = page
            .split("## Stated in prose")
            .nth(1)
            .expect("a prose section");
        assert!(prose.contains("**standing** (claim)"), "{page}");
        for (path, body) in folder.files.iter().chain(&rendered()) {
            assert!(
                !body.contains("`standing`"),
                "{path} names `standing` as a column"
            );
        }
    }

    #[test]
    fn every_page_carries_the_textql_marker_and_no_csv_does() {
        let files = textql().files;
        assert!(textql::MARKER.starts_with(textql::MARKER_PREFIX));
        assert!(files.iter().any(|(p, _)| p.ends_with(".csv")));
        for (path, body) in files {
            let first = body.lines().next().unwrap();
            if path.ends_with(".csv") {
                assert_eq!(
                    first, "value",
                    "{path}: a marker line would be read as data"
                );
            } else {
                assert!(
                    first.contains(textql::MARKER_PREFIX),
                    "{path} has no marker"
                );
            }
        }
    }

    #[test]
    fn the_navigation_row_names_every_class_and_the_prefix() {
        assert_eq!(
            textql().navigation,
            "| Compute instance, Network | `ontology/cloud/README.md` |"
        );
    }

    #[test]
    fn two_renders_are_byte_identical() {
        assert_eq!(rendered(), rendered());
    }

    #[test]
    fn contract_json_is_versioned_and_names_every_table() {
        let (_, body) = rendered()
            .into_iter()
            .find(|(p, _)| p == "contract.json")
            .unwrap();
        let v: serde_json::Value = serde_json::from_str(&body).unwrap();
        assert_eq!(v["format_version"], 1);
        let names: Vec<&str> = v["tables"]
            .as_array()
            .unwrap()
            .iter()
            .map(|t| t["name"].as_str().unwrap())
            .collect();
        assert_eq!(
            names,
            [
                "compute_instance",
                "network",
                "edge_compute_instance__attached_to",
                "vocab_compute_instance__provider"
            ]
        );
    }

    #[test]
    fn a_refusal_lists_every_reason_and_names_the_class() {
        let err = render_warehouse(
            &model(&[
                ("a-b", "{}\n"),
                ("a_b", "{}\n"),
                ("thing", "properties:\n  - name: p\n"),
            ]),
            &Inputs {
                feeds: vec![],
                catalog: BTreeSet::new(),
            },
        )
        .err()
        .unwrap()
        .to_string();
        assert!(err.contains("Nothing was written"), "{err}");
        assert!(err.contains("table `a_b`"), "{err}");
        assert!(err.contains("thing.ont.yml: property `p`"), "{err}");
    }

    #[test]
    fn the_export_reports_the_classes_no_feed_maps() {
        let r = render_warehouse(&fixture(), &inputs()).unwrap();
        assert_eq!(r.feeds, ["gcp-cai"]);
        assert_eq!(r.unmapped, ["network"]);
    }

    #[test]
    fn a_feed_refusal_writes_nothing_and_names_the_file() {
        let mut i = inputs();
        i.feeds[0].text = i.feeds[0]
            .text
            .replace("source: gcp-cloud-asset-inventory", "source: x");
        let err = render_warehouse(&fixture(), &i).err().unwrap().to_string();
        assert!(err.contains("Nothing was written"), "{err}");
        assert!(
            err.contains(".yidam/warehouse/feeds/gcp-cai.yml: classes.compute-instance.source"),
            "{err}"
        );
    }
}
