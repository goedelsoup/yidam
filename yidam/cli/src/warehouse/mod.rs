/// The marker every file this module generates carries on its first line.
pub(crate) const MARKER: &str = "Generated by `yidam export --format warehouse` from this \
                                 corpus's ontology. Regenerate rather than edit; an edited file \
                                 is refused on the next export.";

/// The part of [`MARKER`] a later release may not change, since it is what finds the files.
pub(crate) const MARKER_PREFIX: &str = "Generated by `yidam export --format warehouse`";

/// The generator name the manifest records.
pub(crate) const GENERATOR: &str = "yidam export --format warehouse";

/// The contract's own version: it rises when a reader of `contract.json` would mis-read it.
const CONTRACT_FORMAT_VERSION: u32 = 1;

/// Parse the model's classes the way every other reader of `.ont.yml` does.
pub(crate) fn classes(model: &DomainModel) -> Vec<Class> {
    model
        .classes
        .iter()
        .map(|c| {
            Class::parse(
                format!(".yidam/corpus/{}", c.filename),
                String::from_utf8_lossy(&c.content),
            )
        })
        .collect()
}

/// Derive the contract, turning its refusals into one error that lists them all.
pub(crate) fn contract(model: &DomainModel) -> Result<contract::Contract> {
    match contract::derive(&classes(model)) {
        Ok(c) => Ok(c),
        Err(refusals) => bail!(
            "The ontology cannot be placed in a warehouse contract as it stands. Nothing was \
             written:\n  - {}",
            refusals.join("\n  - ")
        ),
    }
}

fn contract_json(contract: &contract::Contract) -> Result<String> {
    #[derive(serde::Serialize)]
    struct Envelope<'a> {
        #[serde(rename = "$comment")]
        comment: &'a str,
        format_version: u32,
        #[serde(flatten)]
        contract: &'a contract::Contract,
    }
    let mut body = serde_json::to_string_pretty(&Envelope {
        comment: MARKER,
        format_version: CONTRACT_FORMAT_VERSION,
        contract,
    })?;
    body.push('\n');
    Ok(body)
}

/// Where a corpus declares its feeds (§3.1).
pub(crate) const FEEDS_DIR: &str = ".yidam/warehouse/feeds";

/// What the warehouse export reads besides the ontology: the feed files, and the catalog
/// slugs a feed's `source:` must name.
pub(crate) struct Inputs {
    pub feeds: Vec<feeds::FeedSource>,
    pub catalog: BTreeSet<String>,
}

impl Inputs {
    pub(crate) fn load(root: &Path) -> Result<Self> {
        let dir = root.join(FEEDS_DIR);
        let mut feeds = Vec::new();
        if dir.is_dir() {
            for entry in
                std::fs::read_dir(&dir).with_context(|| format!("reading {}", dir.display()))?
            {
                let path = entry?.path();
                if path.extension().and_then(|x| x.to_str()) != Some("yml") {
                    continue;
                }
                let stem = path
                    .file_stem()
                    .and_then(|s| s.to_str())
                    .unwrap_or_default();
                feeds.push(feeds::FeedSource {
                    rel: format!("{FEEDS_DIR}/{stem}.yml"),
                    stem: stem.to_string(),
                    text: std::fs::read_to_string(&path)
                        .with_context(|| format!("reading {}", path.display()))?,
                });
            }
        }
        feeds.sort_by(|a, b| a.stem.cmp(&b.stem));
        let catalog = crate::walk::walk_md_files(&crate::paths::yidam_catalog_dir(root))
            .iter()
            .filter_map(|p| p.file_stem().and_then(|s| s.to_str()).map(String::from))
            .collect();
        Ok(Self { feeds, catalog })
    }
}

/// Where the migrations live. A migration an earlier export wrote is kept, since a pipeline
/// may already have run it (§6).
pub(crate) const HISTORY: &str = "ddl/bigquery/";

/// What the last export left in `out`: its contract, and the next migration number.
struct Previous {
    contract: Option<contract::Contract>,
    next: u32,
}

/// The number a migration file name opens with, if it opens with four digits and `_` or `.`.
fn migration_number(name: &str) -> Option<u32> {
    let digits = name.get(..4)?;
    if !digits.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    matches!(name.as_bytes().get(4), Some(b'_' | b'.')).then(|| digits.parse().ok())?
}

fn previous(out: &Path) -> Result<Previous> {
    #[derive(serde::Deserialize)]
    struct Envelope {
        format_version: u32,
        #[serde(flatten)]
        contract: contract::Contract,
    }
    let path = out.join("contract.json");
    let contract = match std::fs::read(&path) {
        Ok(bytes) => {
            let env: Envelope = serde_json::from_slice(&bytes)
                .with_context(|| format!("reading the last export's {}", path.display()))?;
            if env.format_version != CONTRACT_FORMAT_VERSION {
                bail!(
                    "{} is contract format {}, and this yidam reads format {}. Export with the \
                     yidam that wrote it, or move the folder aside to start a new history.",
                    path.display(),
                    env.format_version,
                    CONTRACT_FORMAT_VERSION
                );
            }
            Some(env.contract)
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
    };
    let mut last = 0;
    for dir in [out.join(HISTORY), out.join(HISTORY).join("breaking")] {
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries {
            let name = entry?.file_name();
            if let Some(n) = name.to_str().and_then(migration_number) {
                last = last.max(n);
            }
        }
    }
    Ok(Previous {
        contract,
        next: last + 1,
    })
}

/// What `export --format warehouse` produced.
pub(crate) struct Rendered {
    /// Every file, as output-relative path and bytes.
    pub files: Vec<(String, Vec<u8>)>,
    /// The migration this export added, if the contract changed.
    pub migration: Option<String>,
    /// The additive changes since the last export, one line each.
    pub changes: Vec<String>,
    /// The breaking changes `--allow-breaking` wrote for review, one line each.
    pub breaking: Vec<String>,
    /// The feeds that were resolved, by name.
    pub feeds: Vec<String>,
    /// Classes no feed maps: coverage, reported and never refused (§3.2).
    pub unmapped: Vec<String>,
}

fn resolve_feeds(contract: &contract::Contract, inputs: &Inputs) -> Result<Vec<feeds::Feed>> {
    match feeds::resolve(&inputs.feeds, contract, &inputs.catalog) {
        Ok(f) => Ok(f),
        Err(refusals) => bail!(
            "A feed does not fit the warehouse contract. Nothing was written:\n  - {}",
            refusals.join("\n  - ")
        ),
    }
}

/// Derive the contract, resolve the feeds against it, and render both, with the migration
/// from the contract the last export left in `out` (§6).
///
/// The first export writes `0001_init.sql`. Every later one diffs against `contract.json`:
/// an additive change becomes the next numbered migration, no change writes none, and a
/// breaking change is refused unless `allow_breaking`, which writes it under `breaking/`.
pub(crate) fn render_warehouse(
    model: &DomainModel,
    inputs: &Inputs,
    out: &Path,
    allow_breaking: bool,
) -> Result<Rendered> {
    let contract = contract(model)?;
    let resolved = resolve_feeds(&contract, inputs)?;
    let previous = previous(out)?;
    let mut files = vec![(
        "contract.json".to_string(),
        contract_json(&contract)?.into_bytes(),
    )];
    let n = format!("{:04}", previous.next);
    let (mut migration, mut changes, mut breaking) = (None, Vec::new(), Vec::new());
    match &previous.contract {
        None => {
            let rel = format!("{HISTORY}{n}_init.sql");
            files.push((rel.clone(), bigquery::render_init(&contract).into_bytes()));
            migration = Some(rel);
        }
        Some(old) => {
            let diff = evolution::diff(old, &contract);
            breaking = diff.breaking.iter().map(|b| b.describe()).collect();
            if !breaking.is_empty() && !allow_breaking {
                let mut lines: Vec<String> = breaking.clone();
                lines.extend(
                    diff.additive
                        .iter()
                        .map(|a| format!("{} (additive, held with the rest)", a.describe())),
                );
                bail!(
                    "The ontology changed in ways the tables already loaded cannot follow \
                     without losing or altering rows. Nothing was written:\n  - {}\n\
                     A rename shows as a removal and an addition. Revert the change, or pass \
                     --allow-breaking to write the breaking statements to \
                     {HISTORY}breaking/{n}.sql for review.",
                    lines.join("\n  - ")
                );
            }
            if !diff.additive.is_empty() {
                let rel = format!("{HISTORY}{n}_{}.sql", diff.slug());
                files.push((
                    rel.clone(),
                    bigquery::render_migration(&n, &diff).into_bytes(),
                ));
                migration = Some(rel);
                changes = diff.additive.iter().map(|a| a.describe()).collect();
            }
            if !diff.breaking.is_empty() {
                files.push((
                    format!("{HISTORY}breaking/{n}.sql"),
                    bigquery::render_breaking(&n, &diff.breaking).into_bytes(),
                ));
            }
        }
    }
    files.extend(
        bigquery::render_feeds(&resolved)
            .into_iter()
            .map(|(p, s)| (p, s.into_bytes())),
    );
    Ok(Rendered {
        files,
        migration,
        changes,
        breaking,
        unmapped: feeds::unmapped(&contract, &resolved),
        feeds: resolved.into_iter().map(|f| f.name).collect(),
    })
}

/// Render the `textql` folder (§5): the same contract and feeds the warehouse export reads,
/// so a page cannot name a column the DDL does not create.
pub(crate) fn render_textql(
    model: &DomainModel,
    inputs: &Inputs,
    prefix: &str,
) -> Result<textql::Folder> {
    let contract = contract(model)?;
    let resolved = resolve_feeds(&contract, inputs)?;
    Ok(textql::render(
        &classes(model),
        &contract,
        &resolved,
        prefix,
    ))
}

