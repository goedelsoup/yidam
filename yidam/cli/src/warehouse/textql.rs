//! RFC-0049 §5: the Markdown and CSV half of the `textql` export (#1398).
//!
//! TextQL's Ontology is a git-synced folder: Ana reads `.md` for definitions and `.csv` for
//! reference data, and finds a file through a folder `README.md` that says "when asked about
//! X → read Y". This renders that folder from the contract, so a page names exactly the
//! tables and columns the DDL creates. It reads the classes too, for what the contract
//! drops: labels, alignment, and the `claim`/`quotation` properties that have no column.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::bigquery::type_name;
use super::contract::{ident, Contract, Table, TableKind, PRECISION_SUFFIX, PROVENANCE};
use super::feeds::{Feed, Mode};
use crate::corpus::Class;

/// The marker every Markdown file carries on its first line, inside an HTML comment.
///
/// The CSVs carry none: TextQL reads a `.csv` as reference data, so a marker line would be a
/// value. The manifest alone records them, and §4's refusal on an edit holds for them as for
/// any other file.
pub(crate) const MARKER: &str = "Generated by `yidam export --format textql` from a corpus's \
                                 ontology. Regenerate rather than edit; an edited file is \
                                 refused on the next export.";

/// The part of [`MARKER`] a later release may not change, since it is what finds the files.
pub(crate) const MARKER_PREFIX: &str = "Generated by `yidam export --format textql`";

/// The generator name the manifest records.
pub(crate) const GENERATOR: &str = "yidam export --format textql";

/// What the export writes, and the row a work-side owner adds to their `ANA.md`.
pub(crate) struct Folder {
    pub files: Vec<(String, String)>,
    pub navigation: String,
}

/// Render the folder. `prefix` is where it sits in the TextQL repository, and appears only
/// in the navigation row, because every link inside the folder is relative.
pub(crate) fn render(
    classes: &[Class],
    contract: &Contract,
    feeds: &[Feed],
    prefix: &str,
) -> Folder {
    let by_name: BTreeMap<&str, &Class> = classes.iter().map(|c| (c.name.as_str(), c)).collect();
    let class_tables: Vec<(&Class, &Table)> = contract
        .tables
        .iter()
        .filter_map(|t| match &t.kind {
            TableKind::Class { class } => by_name.get(class.as_str()).map(|c| (*c, t)),
            _ => None,
        })
        .collect();

    let mut files = vec![
        ("README.md".to_string(), readme(&class_tables)),
        ("warehouse.md".to_string(), warehouse(feeds)),
    ];
    for (class, table) in &class_tables {
        files.push((
            format!("classes/{}.md", class.name),
            class_page(class, table, contract, feeds),
        ));
    }
    for table in &contract.tables {
        if let TableKind::Vocab {
            class,
            property,
            values,
        } = &table.kind
        {
            files.push((format!("vocab/{class}__{property}.csv"), csv(values)));
        }
    }

    let topics: Vec<&str> = class_tables.iter().map(|(c, _)| label(c)).collect();
    let navigation = format!(
        "| {} | `{}/README.md` |",
        cell(&topics.join(", ")),
        prefix.trim_end_matches('/')
    );
    Folder { files, navigation }
}

fn header(title: &str) -> String {
    format!("<!-- {MARKER} -->\n\n# {title}\n\n")
}

fn label(class: &Class) -> &str {
    if class.label.trim().is_empty() {
        &class.name
    } else {
        class.label.trim()
    }
}

/// One line of prose, safe inside a Markdown table cell.
fn cell(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

fn readme(classes: &[(&Class, &Table)]) -> String {
    let mut out = header("Ontology");
    out.push_str(
        "Each class below is a BigQuery table, generated from the same ontology as this \
         folder. Read the class's page before querying its table: the page names every \
         column, the values a column may hold, and the link tables that join it to other \
         classes.\n\n\
         | When asked about | Read |\n|---|---|\n",
    );
    for (class, _) in classes {
        let _ = writeln!(
            out,
            "| {} | [classes/{}.md](classes/{}.md) |",
            cell(label(class)),
            class.name,
            class.name
        );
    }
    out.push_str(
        "| where rows come from, `_origin`, `_loaded_at`, or how a date's precision is read \
         | [warehouse.md](warehouse.md) |\n",
    );
    out
}

fn warehouse(feeds: &[Feed]) -> String {
    let mut out = header("How the warehouse tables are loaded");
    out.push_str(
        "Every class table opens with the same provenance columns, and is keyed on \
         `(id, _origin)`. One thing can therefore have a row per origin: the same `id` from two \
         feeds is two rows, and neither overrides the other.\n\n\
         | Column | Type | Required | Meaning |\n|---|---|---|---|\n",
    );
    for (name, ty, required, description) in PROVENANCE {
        let _ = writeln!(
            out,
            "| `{name}` | {} | {} | {} |",
            type_name(*ty),
            yes_no(*required),
            cell(description)
        );
    }
    let _ = write!(out,
        "\n## Dates\n\n\
         A `date` property is two columns. `<name>` is a `DATE`, and `<name>{PRECISION_SUFFIX}` \
         says how much of it was stated: `year`, `month` or `day`. A date stated only as a year \
         or a month is stored as the first day of that interval, so `2024-01-01` with precision \
         `year` means \"some time in 2024\", not \"1 January\". Compare at the stated precision.\n\n\
         ## Link tables\n\n\
         A table named `edge_<class>__<relationship>` holds one row per link, keyed on \
         `(src_id, dst_id, _origin)`. `src_id` is the `id` of a row in the authoring class's \
         table, loaded by the same origin. `dst_id` is the `id` of a row in the target's \
         table, which another origin may have loaded.\n\n\
         ## Feeds\n\n"
    );
    if feeds.is_empty() {
        out.push_str(
            "No feed is declared, so `_origin` holds only `corpus`: rows exported from the \
             corpus itself.\n",
        );
        return out;
    }
    out.push_str(
        "`_origin` is `corpus` for rows exported from the corpus, and otherwise the name of \
         the feed that loaded the row. A **snapshot** feed replaces its origin's rows on every \
         run, so a row it no longer lands is deleted. An **append** feed only inserts and \
         updates.\n\n\
         | Feed | Mode | Classes | Description |\n|---|---|---|---|\n",
    );
    for feed in feeds {
        let classes: Vec<String> = feed
            .classes
            .iter()
            .map(|c| format!("[{}](classes/{}.md)", c.class, c.class))
            .collect();
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            feed.name,
            mode(feed.mode),
            classes.join(", "),
            cell(&feed.description)
        );
    }
    out
}

fn mode(mode: Mode) -> &'static str {
    match mode {
        Mode::Snapshot => "snapshot",
        Mode::Append => "append",
    }
}

fn yes_no(b: bool) -> &'static str {
    if b {
        "yes"
    } else {
        "no"
    }
}

fn class_page(class: &Class, table: &Table, contract: &Contract, feeds: &[Feed]) -> String {
    let mut out = header(label(class));
    // The class's own description, not the table's: the table falls back to the label, which
    // is already the page's title.
    if !class.description.trim().is_empty() {
        let _ = write!(out, "{}\n\n", class.description.trim());
    }
    let _ = write!(
        out,
        "Table: `{}`, keyed on `(id, _origin)`. It also carries the provenance columns in \
         [warehouse.md](../warehouse.md).\n\n",
        table.name
    );

    if let Some(ft) = &class.foundational_type {
        out.push_str("## Alignment\n\n");
        let _ = write!(out, "- {} `{}`", ft.ontology.trim(), ft.ty.trim());
        if let Some(iri) = ft.iri.as_deref().filter(|i| !i.trim().is_empty()) {
            let _ = write!(out, ": <{}>", iri.trim());
        }
        out.push_str("\n\n");
    }

    let properties: Vec<_> = table
        .columns
        .iter()
        .filter(|c| c.property.is_some())
        .collect();
    out.push_str("## Columns\n\n");
    if properties.is_empty() {
        out.push_str("The class declares no property with a column.\n\n");
    } else {
        out.push_str("| Column | Type | Required | Values | Meaning |\n|---|---|---|---|---|\n");
        for column in properties {
            let values = match column.values.as_deref().and_then(|v| vocab(contract, v)) {
                Some((property, values)) => format!(
                    "{} ([csv](../vocab/{}__{}.csv))",
                    values
                        .iter()
                        .map(|v| format!("`{v}`"))
                        .collect::<Vec<_>>()
                        .join(", "),
                    class.name,
                    property
                ),
                None if column
                    .property
                    .as_deref()
                    .map(|p| format!("{}{PRECISION_SUFFIX}", ident(p)))
                    == Some(column.name.clone()) =>
                {
                    "`year`, `month`, `day`".to_string()
                }
                None => String::new(),
            };
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} | {} |",
                column.name,
                type_name(column.ty),
                yes_no(column.required),
                values,
                cell(&column.description)
            );
        }
        out.push('\n');
    }

    let prose: Vec<_> = class
        .properties
        .iter()
        .filter(|p| matches!(p.r#type.as_str(), "claim" | "quotation"))
        .collect();
    if !prose.is_empty() {
        out.push_str(
            "## Stated in prose, not in the table\n\n\
             These properties are claims or quotations: each states a position with its \
             evidence, and none is a fact a column can hold. No table carries them.\n\n",
        );
        for p in prose {
            let what = cell(&p.description);
            let _ = write!(out, "- **{}** ({})", p.name, p.r#type);
            if !what.is_empty() {
                let _ = write!(out, ": {what}");
            }
            out.push('\n');
        }
        out.push('\n');
    }

    let mut links = Vec::new();
    for t in &contract.tables {
        if let TableKind::Edge {
            class: author,
            relationship,
            targets,
        } = &t.kind
        {
            let names = |set: &mut dyn Iterator<Item = &String>| {
                set.map(|n| format!("[{n}]({n}.md)"))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            if *author == class.name {
                links.push(format!(
                    "| {} | out | {} | `{}` |\n",
                    cell(relationship),
                    names(&mut targets.iter()),
                    t.name
                ));
            }
            if targets.contains(&class.name) {
                links.push(format!(
                    "| {} | in | {} | `{}` |\n",
                    cell(relationship),
                    names(&mut std::iter::once(author)),
                    t.name
                ));
            }
        }
    }
    if !links.is_empty() {
        out.push_str(
            "## Links\n\n\
             `out`: this class's `id` is the link table's `src_id`. `in`: it is the `dst_id`.\n\n\
             | Relationship | Direction | Other class | Link table |\n|---|---|---|---|\n",
        );
        for l in links {
            out.push_str(&l);
        }
        out.push('\n');
    }

    let loaded_by: Vec<String> = feeds
        .iter()
        .filter(|f| f.classes.iter().any(|c| c.class == class.name))
        .map(|f| format!("`{}` ({})", f.name, mode(f.mode)))
        .collect();
    out.push_str("## Loaded by\n\n");
    if loaded_by.is_empty() {
        out.push_str("No feed maps this class.\n");
    } else {
        let _ = writeln!(
            out,
            "{}. See [warehouse.md](../warehouse.md).",
            loaded_by.join(", ")
        );
    }
    out
}

/// The property and values of the `vocab_` table named `name`.
fn vocab<'a>(contract: &'a Contract, name: &str) -> Option<(&'a str, &'a [String])> {
    contract.tables.iter().find_map(|t| match &t.kind {
        TableKind::Vocab {
            property, values, ..
        } if t.name == name => Some((property.as_str(), values.as_slice())),
        _ => None,
    })
}

/// A one-column CSV, quoted per RFC 4180 where a value needs it.
fn csv(values: &[String]) -> String {
    let mut out = String::from("value\n");
    for v in values {
        if v.contains([',', '"', '\n', '\r']) {
            let _ = writeln!(out, "\"{}\"", v.replace('"', "\"\""));
        } else {
            out.push_str(v);
            out.push('\n');
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_value_that_would_break_a_csv_row_is_quoted() {
        let got = csv(&["plain".into(), "a, b".into(), "say \"hi\"".into()]);
        assert_eq!(got, "value\nplain\n\"a, b\"\n\"say \"\"hi\"\"\"\n");
    }

    #[test]
    fn a_table_cell_holds_one_line_and_no_bare_pipe() {
        assert_eq!(cell("a |\n  b"), "a \\| b");
    }
}
